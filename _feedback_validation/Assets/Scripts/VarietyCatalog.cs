        public static IEnumerable<PuzzleEntry> Build()
        {
            for (var kind = 0; kind < 3; kind++)
            {
                var texts = kind == 0 ? Thoughts : kind == 1 ? Proverbs : Riddles;
                for (var i = 0; i < texts.Length; i++)
                {
                    var parts = texts[i].Split('|');
                    yield return new PuzzleEntry {
                        id = "variety_v1_" + kind + "_" + i, mode = PuzzleMode.Classic,
                        text = parts[0], answer = parts.Length > 1 ? parts[1] : "",
                        source = kind == 0 ? "Мысли Совушки" : kind == 1 ? "Народная мудрость" : "Загадки Совушки",
                        kind = kind == 0 ? PuzzleKind.Quotes : kind == 1 ? PuzzleKind.Proverbs : PuzzleKind.Riddles,
                        minimumErudition = PuzzleGenerator.Thresholds[i / 4],
                        authorIndex = -1, themeIndex = -1, bookIndex = -1
                    };
                }
            }
        }
